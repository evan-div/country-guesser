// End-to-end smoke test: plays through the main flows on a phone-sized viewport.
//   npm run e2e            (starts its own dev server)
import { answer, check, COUNTRIES, failed, launch, nameOf, OUT, phonePage, startServer, target, waitPhase } from './lib.mjs'

const server = await startServer()
const browser = await launch()
const shot = (page, name) => page.screenshot({ path: `${OUT}/${name}.png` })

try {
  const { page, errors } = await phonePage(browser)
  await page.goto(server.url)
  await page.waitForFunction(() => window.__atlas?.engine, null, { timeout: 60000 })
  await page.waitForTimeout(1500)
  check(await page.getByRole('heading', { name: /ATLAS/ }).isVisible(), 'home screen renders')
  await shot(page, '01-home')

  console.log('Arcade')
  await page.getByRole('button', { name: /ARCADE/ }).click()
  await waitPhase(page, 'GUESSING')
  check((await page.locator('.globe-label').count()) === 0, 'no label reveals the answer while guessing')
  await shot(page, '02-guessing')

  let code = await target(page)
  await answer(page, nameOf(code).toUpperCase() + '  ')
  await waitPhase(page, 'ANSWER_REVEAL')
  check(await page.getByText('Correct!').isVisible(), `correct answer accepted (${code})`)
  check((await page.evaluate(() => window.__atlas.game.state.session.score)) === 100, 'scored 100 points')
  const labelled = await page
    .locator('.globe-label')
    .first()
    .waitFor({ timeout: 8000 })
    .then(() => true)
    .catch(() => false)
  check(labelled, 'country labelled on the globe during reveal')
  await shot(page, '03-correct')

  await page.getByRole('button', { name: /Next country/ }).click()
  await waitPhase(page, 'GUESSING')
  check((await page.locator('input[name^=atlas-answer]').inputValue()) === '', 'input cleared between rounds')
  await answer(page, 'Narnia')
  await page.waitForTimeout(200)
  check(await page.getByText(/isn't a country we recognize/).isVisible(), 'unknown names get a no-penalty notice')
  check((await page.evaluate(() => window.__atlas.game.state.session.lives)) === 5, 'no life lost for unknown name')

  // Lose all five lives.
  for (let i = 0; i < 5; i++) {
    if (i > 0) {
      await page.getByRole('button', { name: /Next country/ }).click()
      await waitPhase(page, 'GUESSING')
    }
    code = await target(page)
    const wrong = COUNTRIES.find((c) => c.code !== code && !c.neighbors.includes(code)).name
    await answer(page, wrong)
    await waitPhase(page, 'ANSWER_REVEAL')
    if (i === 0) await shot(page, '04-wrong')
  }
  check(await page.getByRole('button', { name: /See results/ }).isVisible(), 'run ends after 5 misses')
  await page.getByRole('button', { name: /See results/ }).click()
  await waitPhase(page, 'GAME_OVER')
  await page.waitForTimeout(1200)
  check(await page.getByText(/Missed · 5/).isVisible(), 'game over lists 5 missed countries')
  check(await page.getByText(/New personal best/).isVisible(), 'first run is a personal best')
  await shot(page, '05-game-over')

  await page.getByRole('button', { name: /Review mistakes/ }).click()
  await shot(page, '06-review')
  await page.getByRole('button', { name: /Echo these now/ }).click()
  await waitPhase(page, 'GUESSING')
  check(await page.getByText(/Echo Rounds/).first().isVisible(), 'Echo Round started from mistakes')
  const echoCode = await target(page)
  const missed = await page.evaluate(() => Object.keys(JSON.parse(localStorage.getItem('atlas-rush:save') ?? '{}').echo ?? {}))
  check(missed.includes(echoCode), 'Echo Round asks a previously missed country')
  for (let i = 0; i < 4; i++) await page.getByRole('button', { name: /^Hint/ }).click()
  await page.waitForTimeout(300)
  await shot(page, '07-echo-hints')
  await page.getByRole('button', { name: 'Reveal' }).click()
  await waitPhase(page, 'ANSWER_REVEAL')
  check(await page.getByText('Answer revealed').isVisible(), 'practice-style reveal works')
  await page.getByRole('button', { name: 'Game menu' }).click()
  await page.getByRole('button', { name: /End session/ }).click()
  await waitPhase(page, 'GAME_OVER')
  await page.getByRole('button', { name: 'Home' }).click()
  await waitPhase(page, 'HOME')

  console.log('World Atlas')
  await page.getByRole('button', { name: /World Atlas/ }).click()
  await page.waitForTimeout(1500)
  check(await page.getByText('of the world discovered').isVisible(), 'atlas shows world progress')
  await shot(page, '08-atlas')
  await page.getByRole('button', { name: /Learning/ }).first().click()
  await page.locator('ul button').first().click()
  await page.waitForTimeout(1500)
  check(await page.getByText('Learning record').isVisible(), 'country detail shows learning record')
  await shot(page, '09-atlas-detail')

  console.log('Persistence')
  await page.reload()
  await page.waitForFunction(() => window.__atlas?.engine, null, { timeout: 60000 })
  await page.waitForTimeout(800)
  const chip = await page.getByRole('button', { name: /\/ 195/ }).innerText()
  check(chip.replace(/\s+/g, ' ').trim().startsWith('1 '), `progress survives a reload (${chip.replace(/\s+/g, ' ')})`)
  check(await page.getByText('5 to review').isVisible().catch(() => false), 'Echo collection survives a reload')

  console.log('Practice + keyboard')
  await page.getByRole('button', { name: /PRACTICE/ }).click()
  await waitPhase(page, 'GUESSING')
  await page.locator('input[name^=atlas-answer]').focus()
  await page.setViewportSize({ width: 390, height: 470 }) // simulates an open on-screen keyboard
  await page.waitForTimeout(900)
  const box = await page.getByRole('button', { name: 'Submit answer' }).boundingBox()
  check(box && box.y + box.height <= 470, 'submit stays visible above the keyboard')
  await shot(page, '10-keyboard')
  await page.setViewportSize({ width: 390, height: 844 })

  console.log('Microstate')
  await page.evaluate(() => window.__atlas.game.quit())
  await waitPhase(page, 'HOME')
  await page.evaluate(() => window.__atlas.game.start('practice', 'country', ['VAT']))
  await waitPhase(page, 'GUESSING')
  await page.waitForTimeout(800)
  check(await page.getByText(/follow the beacon/).isVisible(), 'microstates get a beacon hint')
  await shot(page, '11-vatican')

  console.log('Capital & Neighbors modes')
  await page.evaluate(() => window.__atlas.game.quit())
  await waitPhase(page, 'HOME')
  await page.evaluate(() => window.__atlas.game.start('arcade', 'capital', ['AUS']))
  await waitPhase(page, 'GUESSING')
  check(await page.getByText(/What is the capital of/).isVisible(), 'capital prompt names the country')
  await shot(page, '13-capital')
  await answer(page, 'Sydney')
  await waitPhase(page, 'ANSWER_REVEAL')
  check(await page.getByText('Not quite').isVisible(), 'Sydney is not the capital of Australia')
  await page.getByRole('button', { name: /^Next/ }).click()
  await waitPhase(page, 'GUESSING')
  await answer(page, 'canberra')
  await waitPhase(page, 'ANSWER_REVEAL')
  check(await page.getByText('Correct!').isVisible(), 'Canberra accepted')
  await page.evaluate(() => window.__atlas.game.quit())
  await waitPhase(page, 'HOME')
  await page.evaluate(() => window.__atlas.game.start('practice', 'neighbors', ['DEU']))
  await waitPhase(page, 'GUESSING')
  for (let i = 0; i < 2; i++) await page.getByRole('button', { name: /^Hint/ }).click()
  await page.waitForTimeout(500)
  await shot(page, '14-neighbors-hints')
  await answer(page, 'Czechia')
  await waitPhase(page, 'ANSWER_REVEAL')
  await page.waitForTimeout(600)
  check(await page.getByText('Correct!').isVisible(), 'any land neighbor is accepted')
  check((await page.locator('.globe-label').count()) >= 9, 'all neighbors labelled in the reveal')
  await shot(page, '15-neighbors-reveal')

  check(errors.length === 0, `no runtime errors${errors.length ? ': ' + errors.slice(0, 3).join(' | ') : ''}`)

  console.log('Unlocks')
  const un = await phonePage(browser)
  await un.page.addInitScript((codes) => {
    const records = Object.fromEntries(
      codes.map((c) => [c, { encounters: 1, correct: 1, incorrect: 0, unassistedCorrect: 1, hintsUsed: 0, lastSeen: 1, lastResult: 'correct', firstCorrectAt: 1 }]),
    )
    if (!sessionStorage.getItem('seeded')) {
      localStorage.setItem('atlas-rush:save', JSON.stringify({ version: 1, records }))
      sessionStorage.setItem('seeded', '1')
    }
  }, COUNTRIES.slice(0, 30).map((c) => c.code))
  await un.page.goto(server.url)
  await un.page.waitForFunction(() => window.__atlas?.engine, null, { timeout: 60000 })
  await un.page.waitForTimeout(800)
  check(await un.page.getByText('New mode unlocked').isVisible(), 'unlock celebration appears at 25 unique countries')
  await shot(un.page, '16-unlock')
  await un.page.getByRole('button', { name: /Try Capitals mode/ }).click()
  check(await un.page.getByRole('tab', { name: /Capitals/ }).getAttribute('aria-selected') === 'true', 'Capitals mode selectable')
  check(await un.page.getByRole('tab', { name: /Neighbors/ }).innerText().then((t) => t.includes('30/60')), 'Neighbors shows 30/60 progress')

  console.log('WebGL fallback')
  const fb = await phonePage(browser)
  await fb.page.goto(server.url + '?nowebgl')
  await fb.page.waitForFunction(() => window.__atlas?.engine?.kind === 'canvas', null, { timeout: 30000 })
  await fb.page.getByRole('button', { name: /ARCADE/ }).click()
  await waitPhase(fb.page, 'GUESSING')
  const fbCode = await target(fb.page)
  await answer(fb.page, nameOf(fbCode))
  await waitPhase(fb.page, 'ANSWER_REVEAL')
  check(await fb.page.getByText('Correct!').isVisible(), 'game is playable without WebGL')
  await shot(fb.page, '12-fallback')
  check(fb.errors.length === 0, 'no runtime errors in fallback')
} finally {
  await browser.close()
  server.stop()
}

console.log(failed() ? `\n${failed()} check(s) failed` : '\nAll checks passed')
console.log(`Screenshots: ${OUT}`)
process.exit(failed() ? 1 : 0)
